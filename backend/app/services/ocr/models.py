from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class BoundingBox:
    """Standardized bounding box coordinates (top-left x1, y1 to bottom-right x2, y2)."""
    x1: int
    y1: int
    x2: int
    y2: int

    @property
    def width(self) -> int:
        return max(0, self.x2 - self.x1)

    @property
    def height(self) -> int:
        return max(0, self.y2 - self.y1)

    def to_dict(self) -> Dict[str, int]:
        return {"x1": self.x1, "y1": self.y1, "x2": self.x2, "y2": self.y2}


@dataclass
class OCRRegion:
    """An individual text block/word/line detected with its spatial bounds and confidence."""
    text: str
    confidence: float
    bbox: BoundingBox
    polygon: Optional[List[List[int]]] = None
    angle: float = 0.0
    field_hint: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "text": self.text,
            "confidence": round(float(self.confidence), 4),
            "bbox": self.bbox.to_dict(),
            "polygon": self.polygon,
            "angle": self.angle,
            "field_hint": self.field_hint,
        }


@dataclass
class OCRResultData:
    """Structured result generated by OCR extraction."""
    full_text: str
    confidence_score: float
    regions: List[OCRRegion] = field(default_factory=list)
    raw_payload: Optional[Dict[str, Any]] = None
    engine_name: str = "mock"
    engine_version: str = "1.0.0"
    language: str = "en"
    processing_time_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "full_text": self.full_text,
            "confidence_score": round(float(self.confidence_score), 4),
            "regions": [r.to_dict() for r in self.regions],
            "engine_name": self.engine_name,
            "engine_version": self.engine_version,
            "language": self.language,
            "processing_time_ms": round(self.processing_time_ms, 2),
            "raw_payload": self.raw_payload or {},
        }


@dataclass
class ImageQualityMetrics:
    """Quantitative quality assessment metrics for an input image."""
    sharpness_score: float
    is_blurry: bool
    brightness_mean: float
    is_too_dark: bool
    is_too_bright: bool
    contrast_score: float
    is_low_contrast: bool
    width: int
    height: int
    is_low_resolution: bool
    quality_score: float
    warnings: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "sharpness_score": round(self.sharpness_score, 2),
            "is_blurry": self.is_blurry,
            "brightness_mean": round(self.brightness_mean, 2),
            "is_too_dark": self.is_too_dark,
            "is_too_bright": self.is_too_bright,
            "contrast_score": round(self.contrast_score, 2),
            "is_low_contrast": self.is_low_contrast,
            "width": self.width,
            "height": self.height,
            "is_low_resolution": self.is_low_resolution,
            "quality_score": round(self.quality_score, 2),
            "warnings": self.warnings,
        }


@dataclass
class ImageValidationResult:
    """Result of structural file verification."""
    is_valid: bool
    mime_type: Optional[str] = None
    size_bytes: int = 0
    width: Optional[int] = None
    height: Optional[int] = None
    error_message: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_valid": self.is_valid,
            "mime_type": self.mime_type,
            "size_bytes": self.size_bytes,
            "width": self.width,
            "height": self.height,
            "error_message": self.error_message,
        }
